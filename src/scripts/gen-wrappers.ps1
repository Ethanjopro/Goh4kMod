# Generates forwarding base classes for the COM wrappers from the Windows SDK headers:
#   src/proxy/gen/fwd_device.h     Fwd_ID3D11Device5          (ID3D11Device .. ID3D11Device5)
#   src/proxy/gen/fwd_context.h    Fwd_ID3D11DeviceContext4   (ID3D11DeviceChild, ID3D11DeviceContext .. 4)
#   src/proxy/gen/fwd_swapchain.h  Fwd_IDXGISwapChain4        (IDXGIObject, IDXGIDeviceSubObject, IDXGISwapChain .. 4)
#   src/dxgi/gen/fwd_factory.h     Fwd_IDXGIFactory7          (IDXGIObject, IDXGIFactory .. 7)
# Each class forwards every method except IUnknown's to `m_real`; the hand-written wrappers derive from
# them and override only what they need.
# Usage: powershell -NoProfile -File src\scripts\gen-wrappers.ps1 [-Sdk 10.0.26100.0]
param([string]$Sdk = '10.0.26100.0')
$ErrorActionPreference = 'Stop'
$root = Resolve-Path "$PSScriptRoot\..\.."
$out = Join-Path $root 'src\proxy\gen'
New-Item -ItemType Directory -Force $out | Out-Null
$inc = "${env:ProgramFiles(x86)}\Windows Kits\10\Include\$Sdk"

function Get-Methods([string]$header, [string]$iface) {
    $lines = Get-Content $header
    $start = -1
    for ($i = 0; $i -lt $lines.Count; $i++) { if ($lines[$i] -match "^    $iface : public \w+") { $start = $i; break } }
    if ($start -lt 0) { throw "$iface not found in $header" }
    $end = $start
    while ($lines[$end] -notmatch '^    };') { $end++ }
    $body = ($lines[$start..$end] -join "`n")
    if ($body -match '#if') { throw "$iface has preprocessor blocks; generator would need to handle them" }
    $body = [regex]::Replace($body, '/\*.*?\*/', ' ', 'Singleline')
    $methods = @()
    $rx = [regex]::new('virtual\s+(?<ret>[\w\s\*]+?)\s+STDMETHODCALLTYPE\s+(?<name>\w+)\s*\((?<params>.*?)\)\s*=\s*0\s*;', 'Singleline')
    $declared = ([regex]::Matches($body, 'STDMETHODCALLTYPE')).Count
    if ($rx.Matches($body).Count -ne $declared) { throw "$iface declares $declared methods but only $($rx.Matches($body).Count) parsed" }
    foreach ($m in $rx.Matches($body)) {
        $params = ($m.Groups['params'].Value -replace '\s+', ' ').Trim()
        # split on top-level commas (SAL annotations contain commas inside parentheses)
        $parts = @(); $depth = 0; $cur = ''
        foreach ($ch in $params.ToCharArray()) {
            if ($ch -eq '(') { $depth++ } elseif ($ch -eq ')') { $depth-- }
            if ($ch -eq ',' -and $depth -eq 0) { $parts += $cur.Trim(); $cur = '' } else { $cur += $ch }
        }
        if ($cur.Trim()) { $parts += $cur.Trim() }
        if ($parts.Count -eq 1 -and $parts[0] -eq 'void') { $parts = @() }
        $names = foreach ($p in $parts) {
            $q = $p -replace '\[[^\]]*\]\s*$', ''
            if ($q -notmatch '(\w+)\s*$') { throw "Can't find parameter name in '$p' ($iface)" }
            $Matches[1]
        }
        $methods += [pscustomobject]@{
            Ret = ($m.Groups['ret'].Value -replace '\s+', ' ').Trim()
            Name = $m.Groups['name'].Value
            Params = ($parts -join ', ')
            Args = ($names -join ', ')
        }
    }
    if ($methods.Count -eq 0) { throw "No methods parsed for $iface" }
    $methods
}

function Write-Fwd([string]$file, [string]$class, [string]$top, [array]$chain, [string]$dir = $out) {
    $o = @("// Generated by src/scripts/gen-wrappers.ps1 from Windows SDK $Sdk headers. Do not edit.",
        '#pragma once', '#include <d3d11_4.h>', '#include <dxgi1_6.h>')
    $o += '', "class $class : public $top {", 'protected:', "    $top* m_real = nullptr;", 'public:'
    $total = 0
    foreach ($c in $chain) {
        $ms = @(Get-Methods (Join-Path $inc $c.Header) $c.Iface)
        $o += "    // $($c.Iface)"
        foreach ($m in $ms) {
            $o += "    $($m.Ret) STDMETHODCALLTYPE $($m.Name)($($m.Params)) override { return m_real->$($m.Name)($($m.Args)); }"
        }
        $total += $ms.Count
    }
    $o += '};'
    New-Item -ItemType Directory -Force $dir | Out-Null
    $o | Set-Content -Encoding ascii (Join-Path $dir $file)
    "${class}: $total methods"
}

