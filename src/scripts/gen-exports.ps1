# Generates the d3d11.dll export forwarding for the proxy from `dumpbin /exports` of System32\d3d11.dll:
#   src/proxy/gen/d3d11.def      export table with the system DLL's ordinals
#   src/proxy/gen/exports.asm    ml64 jump stubs for every export we don't implement ourselves
#   src/proxy/gen/exports_gen.h  export names and indices for the C++ side
# Usage (from a shell with dumpbin on PATH, e.g. via start.cmd):
#   powershell -NoProfile -File src\scripts\gen-exports.ps1
param(
    [string]$Dump = "$PSScriptRoot\..\..\scratch\phase1\exports-system32-d3d11.txt"
)
$ErrorActionPreference = 'Stop'
$root = Resolve-Path "$PSScriptRoot\..\.."
$out = Join-Path $root 'src\proxy\gen'
New-Item -ItemType Directory -Force $out | Out-Null

if (-not (Test-Path $Dump)) {
    $Dump = Join-Path $env:TEMP 'goh4k-d3d11-exports.txt'
    & dumpbin /nologo /exports "$env:WINDIR\System32\d3d11.dll" | Set-Content -Encoding ascii $Dump
}

# Exports we implement in C++ (main.cpp); everything else jumps straight to the real DLL.
$implemented = @{ 'D3D11CreateDevice' = 'Proxy_D3D11CreateDevice'; 'D3D11CreateDeviceAndSwapChain' = 'Proxy_D3D11CreateDeviceAndSwapChain' }

$exports = @()
foreach ($line in Get-Content $Dump) {
    if ($line -match '^\s+(\d+)\s+[0-9A-F]+\s+[0-9A-F]{8}\s+(\w+)\s*$') {
        $exports += [pscustomobject]@{ Ordinal = [int]$Matches[1]; Name = $Matches[2] }
    }
}
if ($exports.Count -lt 10) { throw "Parsed only $($exports.Count) exports from $Dump" }

$hdr = "; Generated by src/scripts/gen-exports.ps1 from System32\d3d11.dll exports. Do not edit."
$def = @('; Generated by src/scripts/gen-exports.ps1. Do not edit.', 'LIBRARY d3d11', 'EXPORTS')
$asm = @($hdr, 'EXTERN g_exports:QWORD', 'EXTERN ResolveExports:PROC', '', '.code', '',
    '; Slow path: r11 = export index. Loads the real DLL, then jumps to the real function with the',
    '; caller''s arguments (rcx, rdx, r8, r9, xmm0-3) intact.',
    'ResolveSlow PROC',
    '    push rcx',
    '    push rdx',
    '    push r8',
    '    push r9',
    '    push r11',
    '    sub rsp, 60h',
    '    movdqu xmmword ptr [rsp+20h], xmm0',
    '    movdqu xmmword ptr [rsp+30h], xmm1',
    '    movdqu xmmword ptr [rsp+40h], xmm2',
    '    movdqu xmmword ptr [rsp+50h], xmm3',
    '    call ResolveExports',
    '    movdqu xmm0, xmmword ptr [rsp+20h]',
    '    movdqu xmm1, xmmword ptr [rsp+30h]',
    '    movdqu xmm2, xmmword ptr [rsp+40h]',
    '    movdqu xmm3, xmmword ptr [rsp+50h]',
    '    add rsp, 60h',
    '    pop r11',
    '    pop r9',
    '    pop r8',
    '    pop rdx',
    '    pop rcx',
    '    lea rax, g_exports',
    '    mov rax, qword ptr [rax + r11*8]',
    '    jmp rax',
    'ResolveSlow ENDP', '')
$h = @('// Generated by src/scripts/gen-exports.ps1 from System32\d3d11.dll exports. Do not edit.', '#pragma once', '',
    "#define GOH4K_EXPORT_COUNT $($exports.Count)", '',
    'static const char* const kExportNames[GOH4K_EXPORT_COUNT] = {')
$enum = @('enum ExportIndex {')

for ($i = 0; $i -lt $exports.Count; $i++) {
    $e = $exports[$i]
    $h += "    `"$($e.Name)`","
    $enum += "    EXP_$($e.Name) = $i,"
    if ($implemented.ContainsKey($e.Name)) {
        $def += "    $($e.Name) = $($implemented[$e.Name]) @$($e.Ordinal)"
    } else {
        $def += "    $($e.Name) = Stub_$($e.Name) @$($e.Ordinal)"
        $asm += "Stub_$($e.Name) PROC"
        $asm += "    mov rax, qword ptr [g_exports + $($i * 8)]"
        $asm += '    test rax, rax'
        $asm += "    jz Slow_$i"
        $asm += '    jmp rax'
        $asm += "Slow_$($i):"
        $asm += "    mov r11, $i"
        $asm += '    jmp ResolveSlow'
        $asm += "Stub_$($e.Name) ENDP"
        $asm += ''
    }
}
$h += '};', ''
$enum += '};'
$asm += 'END'

$def | Set-Content -Encoding ascii (Join-Path $out 'd3d11.def')
$asm | Set-Content -Encoding ascii (Join-Path $out 'exports.asm')
($h + $enum) | Set-Content -Encoding ascii (Join-Path $out 'exports_gen.h')
"gen-exports: $($exports.Count) exports, $($implemented.Count) implemented in C++"
