# Generates export forwarding for a proxy DLL from `dumpbin /exports` of the System32 original:
#   <out>/<dll>.def        export table with the system DLL's ordinals (+ our extra exports)
#   <out>/exports.asm      ml64 jump stubs for every export we don't implement ourselves
#   <out>/exports_gen.h    export names and indices for the C++ side
# Usage (dumpbin on PATH, e.g. a start.cmd session):
#   powershell -NoProfile -File src\scripts\gen-exports.ps1 -Dll d3d11
#   powershell -NoProfile -File src\scripts\gen-exports.ps1 -Dll dxgi
param([ValidateSet('d3d11', 'dxgi')][string]$Dll = 'd3d11')
$ErrorActionPreference = 'Stop'
$root = Resolve-Path "$PSScriptRoot\..\.."

$cfg = @{
    d3d11 = @{
        Out = 'src\proxy\gen'
        # Implemented in src/proxy/main.cpp.
        Implemented = @{ 'D3D11CreateDevice' = 'Proxy_D3D11CreateDevice'; 'D3D11CreateDeviceAndSwapChain' = 'Proxy_D3D11CreateDeviceAndSwapChain' }
        # Called by our dxgi.dll proxy (src/dxgi) to hand swapchain creation to the d3d11 proxy.
        Extra = @('Goh4k_CreateSwapChain', 'Goh4k_CreateSwapChainForHwnd', 'Goh4k_LogLine')
    }
    dxgi = @{
        Out = 'src\dxgi\gen'
        Implemented = @{ 'CreateDXGIFactory' = 'Proxy_CreateDXGIFactory'; 'CreateDXGIFactory1' = 'Proxy_CreateDXGIFactory1'; 'CreateDXGIFactory2' = 'Proxy_CreateDXGIFactory2' }
        Extra = @()
    }
}[$Dll]

$out = Join-Path $root $cfg.Out
New-Item -ItemType Directory -Force $out | Out-Null
$dump = Join-Path $root "scratch\phase1\exports-system32-$Dll.txt"
if (-not (Test-Path $dump)) {
    New-Item -ItemType Directory -Force (Split-Path $dump) | Out-Null
    & dumpbin /nologo /exports "$env:WINDIR\System32\$Dll.dll" | Set-Content -Encoding ascii $dump
}

$exports = @()
foreach ($line in Get-Content $dump) {
    if ($line -match '^\s+(\d+)\s+[0-9A-F]+\s+[0-9A-F]{8}\s+(\w+)\s*$') {
        $exports += [pscustomobject]@{ Ordinal = [int]$Matches[1]; Name = $Matches[2] }
    }
}
if ($exports.Count -lt 10) { throw "Parsed only $($exports.Count) exports from $dump" }
foreach ($name in $cfg.Implemented.Keys) {
    if (-not ($exports | Where-Object { $_.Name -eq $name })) { throw "$name is not exported by System32\$Dll.dll" }
}

$def = @('; Generated by src/scripts/gen-exports.ps1. Do not edit.', "LIBRARY $Dll", 'EXPORTS')
$asm = @("; Generated by src/scripts/gen-exports.ps1 from System32\$Dll.dll exports. Do not edit.",
    'EXTERN g_exports:QWORD', 'EXTERN ResolveExports:PROC', '', '.code', '',
    '; Slow path: r11 = export index. Loads the real DLL, then jumps to the real function with the',
    '; caller''s arguments (rcx, rdx, r8, r9, xmm0-3) intact.',
    'ResolveSlow PROC',
    '    push rcx',
    '    push rdx',
    '    push r8',
    '    push r9',
    '    push r11',
    '    sub rsp, 60h',
    '    movdqu xmmword ptr [rsp+20h], xmm0',
    '    movdqu xmmword ptr [rsp+30h], xmm1',
    '    movdqu xmmword ptr [rsp+40h], xmm2',
    '    movdqu xmmword ptr [rsp+50h], xmm3',
    '    call ResolveExports',
    '    movdqu xmm0, xmmword ptr [rsp+20h]',
    '    movdqu xmm1, xmmword ptr [rsp+30h]',
    '    movdqu xmm2, xmmword ptr [rsp+40h]',
    '    movdqu xmm3, xmmword ptr [rsp+50h]',
    '    add rsp, 60h',
    '    pop r11',
    '    pop r9',
    '    pop r8',
    '    pop rdx',
    '    pop rcx',
    '    lea rax, g_exports',
    '    mov rax, qword ptr [rax + r11*8]',
    '    jmp rax',
    'ResolveSlow ENDP', '')
$h = @("// Generated by src/scripts/gen-exports.ps1 from System32\$Dll.dll exports. Do not edit.", '#pragma once', '',
    "#define GOH4K_EXPORT_COUNT $($exports.Count)", "#define GOH4K_REAL_DLL L`"$Dll.dll`"", '',
    'static const char* const kExportNames[GOH4K_EXPORT_COUNT] = {')
$enum = @('enum ExportIndex {')

for ($i = 0; $i -lt $exports.Count; $i++) {
    $e = $exports[$i]
    $h += "    `"$($e.Name)`","
    $enum += "    EXP_$($e.Name) = $i,"
    if ($cfg.Implemented.ContainsKey($e.Name)) {
        $def += "    $($e.Name) = $($cfg.Implemented[$e.Name]) @$($e.Ordinal)"
    } else {
        $def += "    $($e.Name) = Stub_$($e.Name) @$($e.Ordinal)"
        $asm += "Stub_$($e.Name) PROC"
        $asm += "    mov rax, qword ptr [g_exports + $($i * 8)]"
        $asm += '    test rax, rax'
        $asm += "    jz Slow_$i"
        $asm += '    jmp rax'
        $asm += "Slow_$($i):"
        $asm += "    mov r11, $i"
        $asm += '    jmp ResolveSlow'
        $asm += "Stub_$($e.Name) ENDP"
        $asm += ''
    }
}
foreach ($x in $cfg.Extra) { $def += "    $x" }
$h += '};', ''
$enum += '};'
$asm += 'END'

$def | Set-Content -Encoding ascii (Join-Path $out "$Dll.def")
$asm | Set-Content -Encoding ascii (Join-Path $out 'exports.asm')
($h + $enum) | Set-Content -Encoding ascii (Join-Path $out 'exports_gen.h')
"gen-exports ${Dll}: $($exports.Count) exports, $($cfg.Implemented.Count) implemented in C++, $($cfg.Extra.Count) extra"
